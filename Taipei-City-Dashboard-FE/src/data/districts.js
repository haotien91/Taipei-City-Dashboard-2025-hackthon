// 工具函數：根據ID獲取商圈資料
export function getDistrictById(id) {
	return districts.find((district) => district.id === id) || null;
}

// 工具函數：根據行政區獲取商圈列表
export function getDistrictsByArea(area) {
	return districts.filter((district) => district.district === area);
}

// 工具函數：搜尋商圈（名稱或標籤）
export function searchDistricts(query) {
	const lowerQuery = query.toLowerCase();
	return districts.filter(
		(district) =>
			district.name.toLowerCase().includes(lowerQuery) ||
			district.hashtags.some((tag) =>
				tag.toLowerCase().includes(lowerQuery)
			)
	);
}
